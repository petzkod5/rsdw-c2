#!/usr/bin/env node
// Regenerates the login artwork shipped in web/assets and the markup/CSS that references it.
//
//   node scripts/build-login-art.cjs <desktop-source.png> <mobile-source.png>
//
// The 10 MB sources are not in the repository. They live in git history:
//   git show f8dffc9:web/assets/dragonwilds-login-desktop-v1.png > desktop.png
//   git show f8dffc9:web/assets/dragonwilds-login-mobile-v1.png  > mobile.png
//
// Output files are content-hashed (login-hero-<variant>.<sha256[:10]>.<ext>) so the Go handler can serve
// them as immutable. The script rewrites the generated blocks in web/index.html (<picture>) and
// web/styles.css (inline blurred placeholders) between their login-art markers; commit the result.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const assets = path.join(root, 'web/assets');
const [desktopSource, mobileSource] = process.argv.slice(2);
if (!desktopSource || !mobileSource) {
  console.error('usage: node scripts/build-login-art.cjs <desktop-source.png> <mobile-source.png>');
  process.exit(2);
}

const AVIF = {quality: 45, effort: 6};
const WEBP = {quality: 72, effort: 6};
const MAX_IMAGE_BYTES = 250 * 1000;

async function emit(source, name, width, format) {
  const pipeline = sharp(source).resize({width});
  const {data, info} = await (format === 'avif' ? pipeline.avif(AVIF) : pipeline.webp(WEBP)).toBuffer({resolveWithObject: true});
  if (data.length > MAX_IMAGE_BYTES) throw new Error(`${name}-${width}.${format} is ${data.length} bytes, over the ${MAX_IMAGE_BYTES} byte image budget`);
  const hash = crypto.createHash('sha256').update(data).digest('hex').slice(0, 10);
  const file = `login-hero-${name}-${width}.${hash}.${format}`;
  fs.writeFileSync(path.join(assets, file), data);
  console.log(file.padEnd(46), `${info.width}x${info.height}`.padEnd(10), `${(data.length / 1000).toFixed(1)} kB`);
  return {url: `/assets/${file}`, width: info.width, height: info.height};
}

async function placeholder(source) {
  const data = await sharp(source).resize({width: 24}).webp({quality: 40}).toBuffer();
  return `data:image/webp;base64,${data.toString('base64')}`;
}

function replaceBlock(file, begin, end, body) {
  const text = fs.readFileSync(file, 'utf8');
  const start = text.indexOf(begin);
  const stop = text.indexOf(end);
  if (start < 0 || stop < start) throw new Error(`${file}: missing ${begin} ... ${end} markers`);
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  fs.writeFileSync(file, text.slice(0, start + begin.length) + eol + body.replace(/\n/g, eol) + eol + text.slice(stop));
}

const srcset = (variants) => variants.map((v) => `${v.url} ${v.width}w`).join(', ');

(async () => {
  fs.mkdirSync(assets, {recursive: true});
  for (const old of fs.readdirSync(assets)) if (old.startsWith('login-hero-')) fs.rmSync(path.join(assets, old));
  const desktopAvif = [];
  for (const width of [1280, 1920, 2560]) desktopAvif.push(await emit(desktopSource, 'd', width, 'avif'));
  const mobileAvif = [];
  for (const width of [750, 1170]) mobileAvif.push(await emit(mobileSource, 'm', width, 'avif'));
  const desktopWebp = await emit(desktopSource, 'd', 1280, 'webp');
  const mobileWebp = await emit(mobileSource, 'm', 750, 'webp');
  const fallback = desktopWebp;
  const mobileSize = mobileAvif.at(-1);
  const desktopSize = desktopAvif.at(-1);

  const mobileQuery = '(max-width: 760px)';
  const picture = [
    '    <picture>',
    `      <source media="${mobileQuery}" type="image/avif" srcset="${srcset(mobileAvif)}" sizes="100vw" width="${mobileSize.width}" height="${mobileSize.height}">`,
    `      <source media="${mobileQuery}" type="image/webp" srcset="${srcset([mobileWebp])}" sizes="100vw" width="${mobileWebp.width}" height="${mobileWebp.height}">`,
    `      <source type="image/avif" srcset="${srcset(desktopAvif)}" sizes="100vw" width="${desktopSize.width}" height="${desktopSize.height}">`,
    `      <img class="login-art-image" src="${fallback.url}" srcset="${srcset([desktopWebp])}" sizes="100vw" alt="" width="${fallback.width}" height="${fallback.height}" fetchpriority="high" decoding="async">`,
    '    </picture>',
  ].join('\n');
  replaceBlock(path.join(root, 'web/index.html'), '<!-- login-art:begin (generated by scripts/build-login-art.cjs) -->', '<!-- login-art:end -->', picture);

  const css = [
    `.login-art { background-image: url("${await placeholder(desktopSource)}"); }`,
    `@media ${mobileQuery} { .login-art { background-image: url("${await placeholder(mobileSource)}"); } }`,
  ].join('\n');
  replaceBlock(path.join(root, 'web/styles.css'), '/* login-art:begin (generated by scripts/build-login-art.cjs) */', '/* login-art:end */', css);
})().catch((error) => { console.error(error); process.exit(1); });
